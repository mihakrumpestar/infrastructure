func TestParseHostsRejectsInlineSecrets(t *testing.T) {
	for _, key := range []string{
		"password", "ssh_password", "SSH_Password", "gateway_password",
		"ssh_tunnel_password", "ssh_tunnel_passphrase",
	} {
		t.Run(key, func(t *testing.T) {
			_, _, err := ParseHosts(entryWithHosts("host", "u", "server=example "+key+"=nope"))
			if err == nil || !strings.Contains(err.Error(), key) {
				t.Fatalf("error = %v, want rejection of %s", err, key)
			}
		})
	}
}

func TestParseHostsErrors(t *testing.T) {
	cases := map[string]struct {
		hosts string
		want  string
	}{
		"missing server": {"group=Lab", "no server"},
		"two lines":      {"server=a\nserver=b", "exactly 1"},
		"no line":        {"# only a comment\n", "no profile line"},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			_, _, err := ParseHosts(entryWithHosts("host", "u", tc.hosts))
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("error = %v, want %q", err, tc.want)
			}
		})
	}
}

func TestParseHostsLowercasesKeys(t *testing.T) {
	profile, warnings, err := ParseHosts(entryWithHosts("host", "u", `Protocol=VNC Name="X" server=s`))
	if err != nil {
		t.Fatal(err)
	}
	if len(warnings) != 0 {
		t.Fatalf("unexpected warnings: %v", warnings)
	}
	if profile.Name != "X" {
		t.Errorf("name = %q, want X", profile.Name)
	}
	if got := profile.Options["protocol"]; got != "VNC" {
		t.Errorf("protocol = %q, want VNC", got)
	}
	if _, ok := profile.Options["Protocol"]; ok {
		t.Errorf("mixed-case key was stored: %#v", profile.Options)
	}
}

