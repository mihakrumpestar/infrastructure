package remmina

import (
	"strings"
	"testing"

	"keepass-config-gen/internal/keepass"
)

func entryWithHosts(title, username, hosts string) keepass.Entry {
	return keepass.Entry{
		Title:    title,
		Username: username,
		Fields:   map[string]string{"remmina_hosts": hosts},
	}
}

func TestParseHostsDefaults(t *testing.T) {
	profile, warnings, err := ParseHosts(entryWithHosts("Workstation", "alice", "server=192.0.2.10 group=Lab"))
	if err != nil {
		t.Fatal(err)
	}
	if len(warnings) != 0 {
		t.Fatalf("unexpected warnings: %v", warnings)
	}
	if profile.Name != "Workstation" {
		t.Errorf("name = %q, want entry title", profile.Name)
	}
	for key, want := range map[string]string{
		"protocol": "RDP",
		"username": "alice",
		"server":   "192.0.2.10",
		"group":    "Lab",
	} {
		if got := profile.Options[key]; got != want {
			t.Errorf("%s = %q, want %q", key, got, want)
		}
	}
}

