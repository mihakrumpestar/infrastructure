func TestFilenameStableAndSlugged(t *testing.T) {
	entry := keepass.Entry{Title: "My Host.two", UUID: "0123456789abcdef"}
	first := Filename("keepass_", entry)
	if want := "keepass_my_host.two-0123456789abcdef.remmina"; first != want {
		t.Fatalf("got %q, want %q", first, want)
	}
	if second := Filename("keepass_", entry); second != first {
		t.Fatalf("filename not stable: %q != %q", first, second)
	}
	other := entry
	other.UUID = "fedcba9876543210"
	if Filename("keepass_", other) == first {
		t.Fatal("different entries produced the same filename")
	}

	empty := keepass.Entry{Title: "", UUID: "0123456789abcdef"}
	if got, want := Filename("keepass_", empty), "keepass_profile-0123456789abcdef.remmina"; got != want {
		t.Fatalf("empty title = %q, want %q", got, want)
	}
}

func TestRenderOrderAndPassword(t *testing.T) {
	profile := Profile{
		Name: "Workstation",
		Options: map[string]string{
			"quality":          "9",
			"username":         "alice",
			"server":           "192.0.2.10",
			"group":            "Lab",
			"protocol":         "RDP",
			"password":         "must-not-leak",
			"Password":         "must-not-leak-either",
			"SSH_Password":     "must-not-leak-ssh",
			"gateway_password": "must-not-leak-gateway",
		},
	}
	want := "# Generated by remmina-config-gen. Do not edit by hand.\n" +
		"[remmina]\n" +
		"name=Workstation\n" +
		"protocol=RDP\n" +
		"server=192.0.2.10\n" +
		"username=alice\n" +
		"password=.\n" +
		"group=Lab\n" +
		"quality=9\n"
	got := Render(profile)
	if got != want {
		t.Fatalf("Render:\n%s\nwant:\n%s", got, want)
	}
	if strings.Contains(got, "must-not-leak") {
		t.Fatal("password leaked into the profile")
	}
	if strings.Count(got, "password=") != 1 {
		t.Fatalf("password written more than once:\n%s", got)
	}
	if again := Render(profile); again != got {
		t.Fatal("Render is not deterministic")
	}
}

func TestRenderEscapesValues(t *testing.T) {
	profile := Profile{
		Name: "  spaced",
		Options: map[string]string{
			"protocol": "RDP",
			"server":   "a\\b\nc\rd\te",
			"username": "u",
			"note":     " x",
		},
	}
	want := "# Generated by remmina-config-gen. Do not edit by hand.\n" +
		"[remmina]\n" +
		"name=\\s spaced\n" +
		"protocol=RDP\n" +
		`server=a\\b\nc\rd\te` + "\n" +
		"username=u\n" +
		"password=.\n" +
		"note=\\sx\n"
	if got := Render(profile); got != want {
		t.Fatalf("Render:\n%q\nwant:\n%q", got, want)
	}
}

func TestRenderEscapesTrailingSpaces(t *testing.T) {
	profile := Profile{
		Name: "ok",
		Options: map[string]string{
			"protocol": "RDP",
			"server":   "host",
			"username": "u",
			"note":     "x  ",
		},
	}
	got := Render(profile)
	if !strings.Contains(got, "note=x \\s\n") {
		t.Fatalf("trailing space was not escaped:\n%q", got)
	}
}

func TestRenderRejectsNUL(t *testing.T) {
	profile := Profile{
		Name: "ok",
		Options: map[string]string{
			"protocol": "RDP",
			"server":   "host\x00hidden",
			"username": "u",
			"note":     "fine",
		},
	}
	got := Render(profile)
	if strings.ContainsRune(got, 0) || strings.Contains(got, "hidden") || strings.Contains(got, "server=") {
		t.Fatalf("NUL value was not rejected:\n%q", got)
	}
	if !strings.Contains(got, "note=fine") {
		t.Fatalf("valid key missing:\n%s", got)
	}
}

func TestParseHostsRejectsNUL(t *testing.T) {
	_, _, err := ParseHosts(entryWithHosts("host", "u", "server=a\x00b"))
	if err == nil || !strings.Contains(err.Error(), "NUL") {
		t.Fatalf("error = %v, want NUL rejection", err)
	}
	if _, _, err := ParseHosts(entryWithHosts("bad\x00title", "u", "server=a")); err == nil || !strings.Contains(err.Error(), "NUL") {
		t.Fatalf("title with NUL: error = %v", err)
	}
}

func TestValidateUUID(t *testing.T) {
	if err := ValidateUUID("0123456789abcdef0123456789abcdef"); err != nil {
		t.Fatalf("valid UUID rejected: %v", err)
	}
	for name, uuid := range map[string]string{
		"empty":        "",
		"short":        "0123456789abcdef",
		"long":         "0123456789abcdef0123456789abcdef00",
		"not hex":      "zzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz",
		"wrong length": "0123456789abcdef0123456789abcde",
	} {
		t.Run(name, func(t *testing.T) {
			if err := ValidateUUID(uuid); err == nil {
				t.Fatalf("ValidateUUID(%q) accepted an invalid UUID", uuid)
			}
		})
	}
}

func TestValidatePrefix(t *testing.T) {
	valid := []string{"", "keepass_", "a..b", "custom-1."}
	for _, prefix := range valid {
		if err := ValidatePrefix(prefix); err != nil {
			t.Errorf("ValidatePrefix(%q) = %v, want nil", prefix, err)
		}
	}
	invalid := map[string]string{
		"parent":    "../escaped_",
		"nested":    "sub/keepass_",
		"backslash": `sub\keepass_`,
		"absolute":  "/abs",
		"dot":       ".",
		"dot dot":   "..",
		"nul":       "bad\x00prefix",
		"newline":   "bad\nprefix",
		"carriage":  "bad\rprefix",
		"tab":       "bad\tprefix",
	}
	for name, prefix := range invalid {
		t.Run(name, func(t *testing.T) {
			if err := ValidatePrefix(prefix); err == nil {
				t.Fatalf("ValidatePrefix(%q) accepted an unsafe prefix", prefix)
			}
		})
	}
}
